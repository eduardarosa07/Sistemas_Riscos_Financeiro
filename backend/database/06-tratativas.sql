CREATE TABLE IF NOT EXISTS public.ocorrencia_tratativa (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('PLD','FRAUDE','CHARGEBACK')),
 origem_id VARCHAR(120) NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE','EM_ANALISE','AGUARDANDO_PARECER','CONCLUIDA')),
 responsavel_id BIGINT REFERENCES public.usuario(id),
 produto VARCHAR(160), cliente_id VARCHAR(120), data_ocorrencia TIMESTAMP NOT NULL,
 valor NUMERIC(18,2), risco VARCHAR(120), decisao VARCHAR(100), justificativa TEXT,
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 concluido_em TIMESTAMP,
 CONSTRAINT uq_tratativa_origem UNIQUE(categoria, origem_id)
);
CREATE INDEX IF NOT EXISTS idx_tratativa_status_data ON public.ocorrencia_tratativa(status,data_ocorrencia);
CREATE INDEX IF NOT EXISTS idx_tratativa_categoria_data ON public.ocorrencia_tratativa(categoria,data_ocorrencia);
CREATE TABLE IF NOT EXISTS public.ocorrencia_tratativa_evento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ocorrencia_id BIGINT NOT NULL REFERENCES public.ocorrencia_tratativa(id),
 executor_id BIGINT NOT NULL REFERENCES public.usuario(id), executor_nome VARCHAR(150) NOT NULL,
 status_anterior VARCHAR(30),status_novo VARCHAR(30) NOT NULL,acao VARCHAR(40) NOT NULL,
 decisao VARCHAR(100),justificativa TEXT,registrado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_tratativa_evento_ocorrencia ON public.ocorrencia_tratativa_evento(ocorrencia_id,registrado_em);
